def clean_translation(source: str, translations: list[str]) -> str:
    compact = re.sub(r"\s+", "", source)
    if compact in TRANSLATION_OVERRIDES:
        return TRANSLATION_OVERRIDES[compact]
    value = modernize_korean(" ".join(t for t in translations if t))
    value = value.replace("수레바퀴가 소의 발자국을 따르듯", "수레가 바퀴자국을 따라가듯")
    sentences = re.split(r"(?<=[.!?])\s+", value)
    deduped = []
    for sentence in sentences:
        if not deduped or sentence != deduped[-1]:
            deduped.append(sentence)
    return " ".join(deduped).strip()


def title_and_intro(number: int, entries: list[tuple[str, str, str]]):
    _ko, hanja, _theme, _filename = CHAPTERS[number]
    intro_index = next(
        i for i, (source, _t, _n) in enumerate(entries)
        if source.startswith(f"{hanja}者") or re.match(r"^[^，。\s]+品者，", source)
    )
    title = "".join(source for source, _t, _n in entries[:intro_index])
    for paratext in ("法句經", "卷上", "卷下", "尊者法救撰", "吳天竺沙門維祇難等譯"):
        title = title.replace(paratext, "")
    if not title.strip():
        overview = OVERVIEW.read_text(encoding="utf-8")
        section = re.search(
            rf"^## 제{number}품 .*?^### 원문\s*$\n(.*?)(?=^### )",
            overview,
            re.M | re.S,
        )
        if not section:
            raise ValueError(f"overview title not found for chapter {number}")
        source_lines = [line.strip() for line in section.group(1).splitlines() if line.strip()]
        start = next(i for i, line in enumerate(source_lines) if hanja in line)
        title = source_lines[start].replace("法句經", "")
        if "章" not in title and start + 1 < len(source_lines) and source_lines[start + 1].startswith("第"):
            title += source_lines[start + 1]
    return title.strip(), entries[intro_index], entries[intro_index + 1:]


def regroup_body(number: int, entries: list[tuple[str, str, str]]):
    filtered = []
    for source, translation, note in entries:
        compact = re.sub(r"\s+", "", source)
        if compact in {"法句經", "卷上", "卷下", "序", "尊者法救撰", "吳天竺沙門維祇難等譯", "法句經卷下"}:
            if number == 21 and compact == "法句經":
                break
            continue
        filtered.append((source, translation, note))

    atomic: list[tuple[str, str]] = []
    for source, translation, _note in filtered:
        source_parts = split_source(source)
        translations = split_translation(source, translation)
        atomic.extend(zip(source_parts, translations))

    verses = []
    source_buffer = ""
    translation_buffer: list[str] = []
    for source, translation in atomic:
        source_buffer += source
        translation_buffer.append(translation)
        if source.rstrip().endswith("。"):
            verses.append((source_buffer.strip(), clean_translation(source_buffer.strip(), translation_buffer)))
            source_buffer, translation_buffer = "", []
    if source_buffer.strip():
        verses.append((source_buffer.strip(), clean_translation(source_buffer.strip(), translation_buffer)))
    return verses


def short_anchor(translation: str) -> str:
    translation = re.sub(r"^(그러므로|그러나|그리고)\s+", "", translation)
    anchor = re.split(r"[,.!?;:]|그리고 |그러므로 |그러나 ", translation, maxsplit=1)[0].strip()
    return anchor if len(anchor) <= 34 else anchor[:33].rstrip() + "…"


def commentary(number: int, verse_index: int, source: str, translation: str) -> str:
    doctrine, caution = GUIDES[number]
    anchor = short_anchor(translation)
    leads = [
        f"‘{anchor}’라는 표현은 ‘{doctrine}’는 가르침을 구체화한다.",
        f"이 게송은 ‘{anchor}’라는 장면에서 ‘{doctrine}’는 뜻을 드러낸다.",
        f"앞뒤 구절을 함께 읽으면 ‘{anchor}’의 핵심은 ‘{doctrine}’는 데 있다.",
        f"‘{anchor}’에 주목하면 ‘{doctrine}’는 방향이 분명해진다.",
        f"여기서 ‘{anchor}’라는 구절은 ‘{doctrine}’는 사실을 일상의 언어로 보여 준다.",
        f"이 대목의 ‘{anchor}’는 ‘{doctrine}’는 점을 강조한다.",
    ]
    matched = [
        note for rule_index, (keywords, note) in enumerate(SEMANTIC_NOTES)
        if number in RULE_CHAPTERS[rule_index]
        and any(key in source for key in keywords.split("|"))
    ]
    parts = matched[:2] if matched else [leads[(verse_index - 1) % len(leads)]]
    if not matched or verse_index % 3 == 1:
        parts.append(caution + ".")
    return " ".join(dict.fromkeys(parts))


