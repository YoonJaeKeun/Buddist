def split_translation(source: str, translation: str) -> list[str]:
    source_parts = split_source(source)
    count = len(source_parts)
    compact = re.sub(r"\s+", "", source)
    if compact in SPLIT_TRANSLATION_OVERRIDES:
        result = SPLIT_TRANSLATION_OVERRIDES[compact]
        assert len(result) == count, (source, result)
        return result
    if count == 1:
        return [translation]
    sentences = [s.strip() for s in re.findall(r".*?(?:[.!?](?=\s|$)|$)", translation) if s.strip()]
    if len(sentences) == count:
        return sentences
    result = []
    for index in range(count):
        start = round(index * len(sentences) / count)
        end = round((index + 1) * len(sentences) / count)
        result.append(" ".join(sentences[start:end]))
    return result


