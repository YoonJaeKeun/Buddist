def parse_entries(path: Path) -> list[tuple[str, str, str]]:
    if os.environ.get("DHAMMAPADA_BASELINE_HEAD") == "1":
        relative = path.relative_to(ROOT).as_posix()
        text = subprocess.check_output(["git", "show", f"HEAD:{relative}"]).decode("utf-8")
    else:
        text = path.read_text(encoding="utf-8")
    return [(s.strip(), t.strip(), n.strip()) for s, t, n in ENTRY_RE.findall(text)]


